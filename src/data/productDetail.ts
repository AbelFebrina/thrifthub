export function getProductBySlug(slug: string): Product | undefined {
  return detailedProducts.find(p => p.slug === slug);
}

export function getRelatedProducts(currentProductId: number, limit = 4): Product[] {
  const current = detailedProducts.find(p => p.id === currentProductId);
  if (!current) return detailedProducts.slice(0, limit);

  return detailedProducts
    .filter(p => p.id !== currentProductId && (p.category === current.category || p.storeId === current.storeId))
    .slice(0, limit);
}
